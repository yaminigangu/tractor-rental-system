/**
 * Returns all unique searchable and selectable localities (mandals + small villages) for a district
 */
export function getAllLocalitiesForDistrict(dist) {
  return Array.from(new Set([...(dist.mandals || []), ...(dist.villages || [])]));
}

/**
 * Calculates straight-line distance in kilometers using the Haversine formula
 */
export function calculateDistanceKm(lat1, lon1, lat2, lon2) {
  const R = 6371; // Earth's radius in km
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLon = ((lon2 - lon1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos((lat1 * Math.PI) / 180) *
      Math.cos((lat2 * Math.PI) / 180) *
      Math.sin(dLon / 2) *
      Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  const d = R * c;
  return Math.round(d * 10) / 10;
}

/**
 * Helper to get district object by name (English or Telugu or lowercase)
 */
export function findDistrictByName(name) {
  if (!name) return undefined;
  const q = name.toLowerCase().trim();
  return TELANGANA_33_DISTRICTS.find(
    (d) =>
      d.id === q ||
      d.name_en.toLowerCase() === q ||
      d.name_en.toLowerCase().includes(q) ||
      d.name_te.includes(name) ||
      q.includes(d.name_en.toLowerCase())
  );
}

/**
 * Searches across all 33 districts for matching villages, mandals, or districts
 */
export function searchTelanganaPlaces(query, limit = 8) {
  const q = query.trim().toLowerCase();
  if (!q) return [];

  const results = [];
  const seen = new Set();

  for (const dist of TELANGANA_33_DISTRICTS) {
    // 1. Check Mandals
    for (const m of dist.mandals) {
      if (m.toLowerCase().includes(q) && !seen.has(`${dist.name_en}-${m}`)) {
        seen.add(`${dist.name_en}-${m}`);
        results.push({
          place: m,
          district: dist.name_en,
          districtTe: dist.name_te,
          isVillage: false,
        });
        if (results.length >= limit) return results;
      }
    }

    // 2. Check Small Villages
    for (const v of dist.villages) {
      if (v.toLowerCase().includes(q) && !seen.has(`${dist.name_en}-${v}`)) {
        seen.add(`${dist.name_en}-${v}`);
        results.push({
          place: v,
          district: dist.name_en,
          districtTe: dist.name_te,
          isVillage: true,
        });
        if (results.length >= limit) return results;
      }
    }
  }

  return results;
}
